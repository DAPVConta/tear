// Diálogo modal que hospeda o Command (palette global ⌘K).
function CommandDialog({
  children,
  open,
  onOpenChange,
}: {
  children: React.ReactNode;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}) {
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="gap-0 overflow-hidden p-0 shadow-elevated">
        <Command
          // Filtro acento-insensível p/ buscar "joao" achar "João".
          filter={(value, search) => {
            const norm = (s: string) =>
              s
                .toLowerCase()
                .normalize("NFD")
                .replace(/\p{Diacritic}/gu, "");
            return norm(value).includes(norm(search)) ? 1 : 0;
          }}
        >
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  );
}

